import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";

const sourceExtensions = new Set([
  ".go", ".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".vue",
  ".py", ".sh", ".bash", ".sql", ".proto", ".css", ".scss", ".html",
  ".yaml", ".yml", ".json", ".tpl", ".tmpl", ".hcl", ".tf",
]);

// Определяем generated по устойчивому пути/заголовку, а не по случайному слову
// внутри исходника. Результат используется обоими анализаторами.
export function generatedReason(filename, header) {
  if (/(?:^|\/)(?:generated|gen|vendor|node_modules)(?:\/|$)/.test(filename))
    return "generated-or-third-party-directory";
  if (/(?:\.pb\.go|_grpc\.pb\.go|\.gen\.(?:go|ts|js|mjs|json|css)|_gen\.go)$/.test(filename))
    return "generated-filename";
  if (/(?:^|\/)(?:package-lock\.json|npm-shrinkwrap\.json|pnpm-lock\.yaml)$/.test(filename))
    return "generated-dependency-lock";
  for (const line of header.split(/\r?\n/)) {
    if (!line.trim()) continue;
    if (!/^\s*(?:\/\/|#|\/\*|\*|<!--|--)/.test(line)) break;
    if (/^\s*(?:\/\/|#|\/\*|\*|<!--|--)\s*(?:Code generated\b[^\n]*DO NOT EDIT|(?:This file (?:is|was) |Automatically )?generated by\b|auto-generated\b)/i.test(line))
      return "generated-header";
  }
  return undefined;
}

export function inventory(root) {
  const filenames = execFileSync("git", ["ls-files", "--cached", "--others", "--exclude-standard", "-z"], {
    cwd: root, encoding: "utf8", maxBuffer: 16 * 1024 * 1024,
  }).split("\0").filter(Boolean);
  const sources = [], excluded = [];
  for (const filename of [...new Set(filenames)].sort()) {
    if (!sourceExtensions.has(path.extname(filename)) && !/(?:^|\/)Dockerfile(?:\.[^/]*)?$/.test(filename)) continue;
    const fullPath = path.join(root, filename);
    const info = fs.lstatSync(fullPath);
    if (!info.isFile()) throw Error("Source inventory requires regular files: " + filename);
    const fd = fs.openSync(fullPath, fs.constants.O_RDONLY | fs.constants.O_NOFOLLOW);
    let header;
    try {
      const buffer = Buffer.alloc(Math.min(4096, info.size));
      fs.readSync(fd, buffer, 0, buffer.length, 0);
      header = buffer.toString("utf8");
    } finally { fs.closeSync(fd); }
    const reason = generatedReason(filename, header);
    if (reason) excluded.push({ path: filename, reason });
    else sources.push(filename);
  }
  return { sources, excluded };
}
