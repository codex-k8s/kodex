import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import test from "node:test";
import { generatedReason, inventory } from "./source-inventory.mjs";

test("inventory handles tracked deletion without hiding new source or symlinks", () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "kodex-inventory-"));
  try {
    execFileSync("git", ["init", "-q"], { cwd: root });
    for (const name of ["removed.go", "tracked.go"]) {
      fs.writeFileSync(path.join(root, name), "package example\n");
    }
    execFileSync("git", ["add", "--", "removed.go", "tracked.go"], { cwd: root });
    fs.unlinkSync(path.join(root, "removed.go"));
    fs.writeFileSync(path.join(root, "new.go"), "package example\n");
    fs.writeFileSync(path.join(root, "wire.pb.go"), "package example\n");
    assert.deepEqual(inventory(root), {
      sources: ["new.go", "tracked.go"],
      excluded: [{ path: "wire.pb.go", reason: "generated-filename" }],
    });
    fs.symlinkSync("tracked.go", path.join(root, "linked.go"));
    assert.throws(() => inventory(root), /requires regular files/);
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
});

test("generated outputs are excluded independently of their language", () => {
  for (const filename of [
    "libs/go/api/gen/v1/api.pb.go",
    "ui/shared/api/generated/types.ts",
    "service/events.gen.go",
    "pkg/shipped_gen.go",
  ])
    assert.ok(generatedReason(filename, "package example"));
  assert.equal(
    generatedReason(
      "api/wire.go",
      "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage example",
    ),
    "generated-header",
  );
  assert.equal(
    generatedReason(
      "ui/models.ts",
      "// This file was generated by openapi-ts\n",
    ),
    "generated-header",
  );
  assert.equal(
    generatedReason("tools/package-lock.json", "{}"),
    "generated-dependency-lock",
  );
});

test("handwritten generators and prose mentioning generation stay in scope", () => {
  for (const filename of [
    "tools/codegen/main.go",
    "pkg/generator.go",
    "pkg/generated_revision.go",
  ])
    assert.equal(
      generatedReason(
        filename,
        "// Generate validates the caller before generating a revision.\npackage generator",
      ),
      undefined,
    );
  assert.equal(
    generatedReason(
      "pkg/example_test.go",
      'const example = "Code generated by fake. DO NOT EDIT."',
    ),
    undefined,
  );
  assert.equal(
    generatedReason(
      "pkg/fixture_test.go",
      "package example\nconst fixture = `\n// Code generated by fake. DO NOT EDIT.\n`",
    ),
    undefined,
  );
  assert.equal(
    generatedReason("buf.gen.yaml", "version: v2\nplugins: []"),
    undefined,
  );
});

test("only proven design exports and built artboards are excluded", () => {
  assert.equal(
    generatedReason("docs/design/kodex-live-run.html", "<!doctype html>"),
    "generated-design-canvas-export",
  );
  assert.equal(
    generatedReason("docs/design/kodex-mockups.html", "<!doctype html>"),
    "generated-design-canvas-export",
  );
  assert.equal(
    generatedReason(
      "docs/design/mockups/01_onboarding_desktop.dc.html",
      "<!doctype html>",
    ),
    "generated-design-artboard",
  );
  assert.equal(
    generatedReason(
      "docs/design/mockups/12_live_run_mobile.dc.html",
      "<!doctype html>",
    ),
    "generated-design-artboard",
  );
  assert.equal(
    generatedReason("docs/design/mockups/Main.dc.html", "<!doctype html>"),
    "generated-design-artboard",
  );
  assert.equal(
    generatedReason("docs/design/mockups/canvas.json", "{}"),
    "generated-design-artboard",
  );
  for (const filename of [
    "docs/design/mockups/12_live_run_desktop.dc.html",
    "docs/design/mockups/VariantB.dc.html",
    "docs/design/mockups/_d01.mjs",
    "docs/design/mvp-redesign/live-run-desktop.html",
    "docs/examples/kodex-live-run.html",
  ])
    assert.equal(generatedReason(filename, "<!doctype html>"), undefined);
});
